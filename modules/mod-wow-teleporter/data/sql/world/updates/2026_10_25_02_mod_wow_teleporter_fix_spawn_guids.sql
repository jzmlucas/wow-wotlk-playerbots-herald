-- AzerothCore creature spawn GUIDs must fit the low GUID range used by ObjectGuid.
-- Move the module's existing high GUIDs into an unused range below 0x00FFFFFF.
UPDATE `creature`
SET `guid` = CASE `guid`
    WHEN 900100000 THEN 9001000
    WHEN 900100001 THEN 9001001
    WHEN 900100002 THEN 9001002
    WHEN 900100003 THEN 9001003
    WHEN 900100004 THEN 9001004
    WHEN 900100005 THEN 9001005
    WHEN 900100006 THEN 9001006
    WHEN 900100007 THEN 9001007
    WHEN 900100008 THEN 9001008
END
WHERE `guid` IN (900100000, 900100001, 900100002, 900100003, 900100004, 900100005, 900100006, 900100007, 900100008);
